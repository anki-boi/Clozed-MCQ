"""Build the Anki templates and the preview page from src/.

    python build.py

Writes front.html and back.html (paste these into Anki's card template
editor) and preview/preview.html (open in a browser to try the templates
against sample notes without Anki).
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).parent
SRC = ROOT / "src"
BANNER = "<!-- Generated by build.py from src/. Edit the files in src/, not this one. -->\n"
FIELDS = {"Text", "Back Extra"}


def read(path: Path) -> str:
    return path.read_text(encoding="utf-8")


def fill(template: str, parts: dict) -> str:
    for marker, text in parts.items():
        if marker not in template:
            raise SystemExit(f"marker {marker} missing from template")
        template = template.replace(marker, text.strip())
    return template


def check_tags(name: str, template: str) -> None:
    """Anki parses every {{...}} in a template, even inside script comments,
    and refuses the template if one names a field the note type lacks."""
    for tag in re.findall(r"\{\{(.*?)\}\}", template, flags=re.S):
        field = tag.lstrip("#^/").split(":")[-1].strip()
        if field not in FIELDS:
            raise SystemExit(f"{name}: '{{{{{tag}}}}}' is not a field of this note type; Anki will reject it")


def main() -> None:
    parts = {
        "/* @PERSISTENCE@ */": read(SRC / "persistence.js"),
        "/* @CORE@ */": read(SRC / "core.js"),
    }
    built = {}
    for side in ("front", "back"):
        built[side] = fill(read(SRC / f"{side}.html"), parts)
        check_tags(f"{side}.html", built[side])
        (ROOT / f"{side}.html").write_text(BANNER + built[side], encoding="utf-8", newline="\n")

    payload = json.dumps(
        {"front": built["front"], "back": built["back"], "css": read(ROOT / "styling.css")},
        ensure_ascii=False,
    ).replace("</", "<\\/")
    preview = fill(read(ROOT / "preview" / "preview.src.html"), {"/* @TEMPLATES@ */": f"const TEMPLATES = {payload};"})
    (ROOT / "preview" / "preview.html").write_text(preview, encoding="utf-8", newline="\n")
    print("built front.html, back.html, preview/preview.html")


if __name__ == "__main__":
    main()
