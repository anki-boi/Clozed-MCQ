"""Build the Anki templates, the importable deck and the preview page from src/.

    python build.py

Writes:
  front.html, back.html     paste into Anki's card template editor
  dist/Clozed-MCQ.apkg      import into Anki: note type with every field, plus example notes
  preview/preview.html      open in a browser to try the templates without Anki

The .apkg needs genanki (pip install genanki); the rest builds without it.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).parent
SRC = ROOT / "src"
BANNER = "<!-- Generated by build.py from src/. Edit the files in src/, not this one. -->\n"

# Field names follow the AnKing Overhaul cloze note type so Change Note Type
# maps them by name and drops nothing. Anki's own Cloze has Text and Back Extra;
# AnKing's "Extra" has no name match and falls into Back Extra, the first
# unmatched field.
FIELDS = [
    "Text", "Back Extra",
    "Lecture Notes", "Missed Questions", "Pathoma", "Boards and Beyond", "First Aid",
    "Sketchy", "Sketchy 2", "Sketchy Extra", "Picmonic", "Pixorize", "Physeo",
    "Bootcamp", "OME", "Additional Resources",
    "One by one",   # AnKing's one-by-one switch; kept so migrations lose nothing, not shown
]
# Shown on the back as buttons that open in place, like the AnKing note type
RESOURCES = FIELDS[2:-1]
# Built in to every note type
SPECIAL_FIELDS = {"Tags"}

# Fixed so re-importing the .apkg updates the same note type and deck
MODEL_ID = 1730846190
DECK_ID = 1730846191
MODEL_NAME = "Clozed MCQ"
DECK_NAME = "Clozed MCQ Examples"

EXAMPLES = [
    ("{{c1::Metformin;;Phenformin;;Buformin;;Glipizide}} is first-line for type 2 diabetes because it "
     "{{c2::reduces hepatic {{c3::gluconeogenesis;;glycogenolysis;;lipolysis;;ketogenesis}};;increases insulin release;;"
     "slows gastric emptying;;blocks renal glucose reabsorption}}.",
     "Rationale: metformin activates AMPK and lowers hepatic glucose output.",
     {"Lecture Notes": "Biguanides: first-line unless contraindicated (eGFR &lt; 30).",
      "Pixorize": "Picture the metformin mnemonic here."}),
    ("The Na<sup>+</sup>/K<sup>+</sup> ATPase pumps 3 {{c1::Na+;;K+;;Ca2+;;Cl-}} out and 2 {{c1::K+;;Na+;;H+}} in per ATP.",
     "Net result: the cell interior becomes more negative.", {}),
    ("Glycolysis: glucose is phosphorylated by {{c1::hexokinase}}, rearranged by {{c1::phosphoglucose isomerase}}, "
     "then committed by {{c1::phosphofructokinase-1}}.",
     "No ;; anywhere: each blank borrows the other answers as choices.", {}),
    ("{{c1::Canberra}} was founded in {{c2::1913}}.",
     "No choices: this works exactly like Anki's own cloze.", {}),
]


def read(path: Path) -> str:
    return path.read_text(encoding="utf-8")


def fill(template: str, parts: dict) -> str:
    for marker, text in parts.items():
        if marker not in template:
            raise SystemExit(f"marker {marker} missing from template")
        template = template.replace(marker, text.strip())
    return template


def check_tags(name: str, template: str) -> None:
    """Anki parses every {{...}} in a template, even inside script comments,
    and refuses the template if one names a field the note type lacks."""
    for tag in re.findall(r"\{\{(.*?)\}\}", template, flags=re.S):
        field = tag.lstrip("#^/").split(":")[-1].strip()
        if field not in FIELDS and field not in SPECIAL_FIELDS:
            raise SystemExit(f"{name}: '{{{{{tag}}}}}' is not a field of this note type; Anki will reject it")


def resource_blocks() -> str:
    """One button per resource field, rendered only when the field has content.
    The field's HTML goes in untouched, so links and images work as in AnKing."""
    return "\n".join(
        f'{{{{#{f}}}}}<div class="cmcq-res" data-name="{f}">'
        f'<button type="button" class="cmcq-res-btn">{f}</button>'
        f'<div class="cmcq-res-body" dir="auto" hidden>{{{{{f}}}}}</div></div>{{{{/{f}}}}}'
        for f in RESOURCES
    )


def build_apkg(front: str, back: str, css: str) -> None:
    try:
        import genanki
    except ImportError:
        print("skipped dist/Clozed-MCQ.apkg (pip install genanki to build it)")
        return
    model = genanki.Model(
        MODEL_ID, MODEL_NAME,
        fields=[{"name": f} for f in FIELDS],
        templates=[{"name": "Cloze", "qfmt": front, "afmt": back}],
        css=css,
        model_type=genanki.Model.CLOZE,
    )
    class ClozeNote(genanki.Note):
        # genanki's own scan misses nested clozes and c1,2 style numbers; count every opener
        def _cloze_cards(self):
            text = self.fields[FIELDS.index("Text")]
            ords = {int(n) - 1 for group in re.findall(r"\{\{c(\d+(?:,\d+)*)::", text) for n in group.split(",")}
            return [genanki.Card(o) for o in sorted(ords or {0})]

    deck = genanki.Deck(DECK_ID, DECK_NAME)
    for text, extra, more in EXAMPLES:
        values = {"Text": text, "Back Extra": extra, **more}
        deck.add_note(ClozeNote(model=model, fields=[values.get(f, "") for f in FIELDS], tags=["clozed-mcq-example"]))
    (ROOT / "dist").mkdir(exist_ok=True)
    genanki.Package(deck).write_to_file(ROOT / "dist" / "Clozed-MCQ.apkg")
    print("built dist/Clozed-MCQ.apkg")


def main() -> None:
    parts = {
        "/* @PERSISTENCE@ */": read(SRC / "persistence.js"),
        "/* @CORE@ */": read(SRC / "core.js"),
    }
    built = {}
    for side in ("front", "back"):
        side_parts = dict(parts, **({"<!-- @RESOURCES@ -->": resource_blocks()} if side == "back" else {}))
        built[side] = fill(read(SRC / f"{side}.html"), side_parts)
        check_tags(f"{side}.html", built[side])
        (ROOT / f"{side}.html").write_text(BANNER + built[side], encoding="utf-8", newline="\n")
    print("built front.html, back.html")

    css = read(ROOT / "styling.css")
    build_apkg(built["front"], built["back"], css)

    payload = json.dumps(
        {"front": built["front"], "back": built["back"], "css": css, "fields": FIELDS},
        ensure_ascii=False,
    ).replace("</", "<\\/")
    preview = fill(read(ROOT / "preview" / "preview.src.html"), {"/* @TEMPLATES@ */": f"const TEMPLATES = {payload};"})
    (ROOT / "preview" / "preview.html").write_text(preview, encoding="utf-8", newline="\n")
    print("built preview/preview.html")


if __name__ == "__main__":
    main()
